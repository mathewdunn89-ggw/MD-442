#!/usr/bin/env node
// Turns the web app's MD|187 and MD|888 patterns (VPRESETS, VSOUND and PTRIM in md442.js) into src/Styles.h, so the plugin
// plays the same patterns with the same sound and loudness. Run: node tools/gen_styles.js path/to/md442.js   (from plugin/)
const fs = require('fs'), path = require('path');
const src = fs.readFileSync(process.argv[2], 'utf8');
const grab = name => { const i = src.indexOf('const ' + name + ' = {'); let j = src.indexOf('{', i), d = 0, k = j; for (; k < src.length; k++) { if (src[k] === '{') d++; else if (src[k] === '}' && --d === 0) break; } return eval('(' + src.slice(j, k + 1) + ')'); };
const VPRESETS = grab('VPRESETS'), VSOUND = grab('VSOUND'), PTRIM = grab('PTRIM');
const KEYS = ['BD', 'SD', 'CP', 'RS', 'LT', 'MT', 'HT', 'CH', 'OH', 'CR', 'RD', 'BS', 'ST', 'AC'];
const clamp = (v, a, b) => Math.min(b, Math.max(a, v));
const out = ['// Generated by tools/gen_styles.js from the web app\'s md442.js (VPRESETS, VSOUND, PTRIM). Do not edit by hand.', '#pragma once', '#include "Presets.h"', '', 'namespace md442 {', '',
  'struct StylePreset { const char* name; const char* style; std::vector<std::pair<const char*, double>> P; std::array<const char*, NUM_KEYS> g; std::array<int, 16> n; const char* brk; double trim; };',
  'inline const std::vector<StylePreset>& stylePresets() {', '    static const std::vector<StylePreset> S {'];
Object.keys(VPRESETS).forEach(name => {
  const p = VPRESETS[name], P = {};
  Object.entries(VSOUND[p.k || p.s]).forEach(([k, v]) => { P[k.replace(/\.SM$/, '.BRK')] = v; });   // the sampler is the plugin's BREAK row
  if (p.bpm) P.bpm = p.bpm; P.shuffle = Math.round(50 + p.sw / 4);
  P['brk.kit'] = p.bk < 4 ? 1 : 2; P['brk.slot'] = p.bk % 4; P['brk.level'] = p.lv; P['brk.complex'] = p.cx;
  const rows = {}; KEYS.forEach(k => { rows[k] = (p.g[k] || '.'.repeat(16)); }); if (p.ac) rows.AC = p.ac;
  const root = p.root || (p.s === '888' ? 45 : 38); P.key = ((root - 28) % 12 + 12) % 12; const oct = 12 * Math.floor((root - 28) / 12);
  const n = Array(16).fill(0); let bs = '';
  (p.bs || Array(16).fill('.')).forEach((c, i) => { if (c === '.') { bs += '.'; return; } bs += 'x'; n[i] = clamp(parseInt(c.replace(/^[asA]/, ''), 10) + oct, -24, 24); });
  rows.BS = bs;
  out.push('        {"' + name + '", "MD' + p.s + '", {' + Object.entries(P).map(([k, v]) => '{"' + k + '", ' + v + '}').join(', ') + '},\n         {' + KEYS.map(k => '"' + rows[k] + '"').join(', ') + '},\n         {' + n.join(', ') + '}, "' + p.br + '", ' + (PTRIM[name] || 0) + '},');
});
out.push('    };', '    return S;', '}', '', '} // namespace md442', '');
fs.writeFileSync(path.join(__dirname, '..', 'src', 'Styles.h'), out.join('\n'));
console.log('wrote src/Styles.h: ' + Object.keys(VPRESETS).length + ' patterns');
