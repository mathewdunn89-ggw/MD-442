#!/usr/bin/env python3
"""Turns styles/md187-md888-presets.json (the performance firmware's MD187 and MD888 patterns) into src/Styles.h.
Run: python3 tools/gen_styles.py   (from plugin/). Trims come from styles/trims.json (dB, so every pattern plays at the same loudness)."""
import json, os
here = os.path.dirname(os.path.abspath(__file__)); root = os.path.dirname(here)
d = json.load(open(os.path.join(root, 'styles', 'md187-md888-presets.json')))
trims = json.load(open(os.path.join(root, 'styles', 'trims.json'))) if os.path.exists(os.path.join(root, 'styles', 'trims.json')) else {}
KEYS = ['BD', 'SD', 'CP', 'RS', 'LT', 'MT', 'HT', 'CH', 'OH', 'CR', 'RD', 'BS', 'ST', 'AC']
# the sound of each style, on top of MD|442's defaults (the firmware uses its own 808/909/303 voicing; these get close to it)
SOUND = {
  'MD187': {'bd.tune': 46, 'bd.decay': 700, 'bd.attack': 40, 'bd.punch': 30, 'bd.rumble': 0, 'sd.tune': -1, 'sd.tone': 35, 'sd.snappy': 55, 'sd.decay': 260,
            'hh.tone': 35, 'ch.decay': 60, 'oh.decay': 420, 'rs.tune': -2, 'cp.tone': 1100, 'flt.CH': -25, 'flt.OH': -25,
            'bs.cutoff': 380, 'bs.reso': 20, 'bs.acid': 0, 'bs.decay': 300, 'bs.drive': 15, 'lvl.BS': -5, 'fx.verb': 15, 'fx.vdec': 1.2},
  'MD888': {'bd.tune': 52, 'bd.decay': 450, 'bd.attack': 75, 'bd.punch': 85, 'bd.rumble': 85, 'drv.BD': 25, 'sd.snappy': 75, 'hh.tone': 70, 'ch.decay': 45,
            'oh.decay': 300, 'cp.decay': 250, 'cp.tone': 1500, 'lt.tune': 2, 'mt.tune': 2, 'ht.tune': 2,
            'bs.cutoff': 400, 'bs.reso': 70, 'bs.acid': 85, 'bs.decay': 160, 'bs.drive': 50, 'fx.drive': 12, 'fx.verb': 20, 'fx.vdec': 2.0},
}
KIT = {'MD187': 1, 'MD888': 2}
out = ['// Generated by tools/gen_styles.py from styles/md187-md888-presets.json. Do not edit by hand.', '#pragma once', '#include "Presets.h"', '', 'namespace md442 {', '',
       'struct StylePreset { const char* name; const char* style; std::vector<std::pair<const char*, double>> P; std::array<const char*, NUM_KEYS> g; std::array<int, 16> n; const char* brk; double trim; };',
       'inline const std::vector<StylePreset>& stylePresets() {', '    static const std::vector<StylePreset> S {']
for style in ['MD187', 'MD888']:
    for p in d[style]['patterns']:
        rows = {k: '.' * 16 for k in KEYS}
        for part in ('d808', 'd909'):
            for k, s in p.get(part, {}).items():
                rows[k] = ''.join('x' if a == 'x' or b == 'x' else '.' for a, b in zip(rows[k], s))
        acc = p.get('acc909') or p.get('acc808')
        if acc: rows['AC'] = acc
        notes = [0] * 16; P = dict(SOUND[style])
        bpm = p.get('bpm', d[style]['bpm'])
        P.update({'bpm': bpm, 'shuffle': round(50 + p.get('swing', 0) * .25)})
        b = p.get('bass')
        if b:
            P['key'] = (b['root'] - 28) % 12
            r = ''
            for i, c in enumerate(b['row']):
                c = c.replace('a', '').replace('s', '')
                if c == '.': r += '.'
                else: r += 'x'; notes[i] = int(c)
            rows['BS'] = r
        brk = p.get('brk')
        if brk:
            P.update({'brk.kit': KIT[style], 'brk.slot': brk['slot'], 'brk.level': brk['level'], 'brk.complex': brk['complex']})
            bs = brk['steps']
        else: bs = '.' * 16
        name = p['name'].title()
        tr = trims.get(style + ' ' + name, 0)
        Ps = ', '.join('{"%s", %g}' % (k, v) for k, v in P.items())
        g = ', '.join('"%s"' % rows[k] for k in KEYS)
        out.append('        {"%s", "%s", {%s},\n         {%s},\n         {%s}, "%s", %g},' % (name, style, Ps, g, ', '.join(map(str, notes)), bs, tr))
out += ['    };', '    return S;', '}', '', '} // namespace md442', '']
open(os.path.join(root, 'src', 'Styles.h'), 'w').write('\n'.join(out))
print('wrote src/Styles.h')
